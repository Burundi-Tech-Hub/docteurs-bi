function translator(lang) {
  const d = dict[lang] || dict.fr;
  return (key, vars = {}) => {
    const s = d[key] ?? dict.fr[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
}

